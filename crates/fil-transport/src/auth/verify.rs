//! The two rustls verifiers. See `docs/m1/quic-auth.md`.

use rustls::client::danger::{HandshakeSignatureValid, ServerCertVerified, ServerCertVerifier};
use rustls::crypto::{self, WebPkiSupportedAlgorithms};
use rustls::pki_types::{CertificateDer, ServerName, SubjectPublicKeyInfoDer, UnixTime};
use rustls::server::danger::{ClientCertVerified, ClientCertVerifier};
use rustls::{DigitallySignedStruct, DistinguishedName, Error, PeerIncompatible, SignatureScheme};

use super::{Fingerprint, KeyRegistry, PublicKey};

/// The only handshake signature scheme either side offers or accepts. Both sides' keys are
/// ECDSA P-256 (generated by this crate), so there is nothing to negotiate.
const SCHEME: SignatureScheme = SignatureScheme::ECDSA_NISTP256_SHA256;

fn algorithms() -> WebPkiSupportedAlgorithms {
    crypto::ring::default_provider().signature_verification_algorithms
}

fn check_scheme(dss: &DigitallySignedStruct) -> Result<(), Error> {
    if dss.scheme == SCHEME {
        Ok(())
    } else {
        Err(Error::PeerIncompatible(
            PeerIncompatible::NoSignatureSchemesInCommon,
        ))
    }
}

fn no_tls12() -> Error {
    Error::PeerIncompatible(PeerIncompatible::Tls12NotOffered)
}

/// Client side: accepts exactly one server certificate, the one whose SHA-256 matches the pin.
///
/// - **Pin, not chain.** There is no CA. `verify_server_cert` compares the end-entity
///   certificate's SHA-256 with the pin and does nothing else: no chain building, no validity
///   dates, no hostname or SNI check, no OCSP. The fingerprint arrived over the authenticated
///   pipe, so a match means "this is the certificate the daemon announced".
/// - **Intermediates are rejected.** The daemon sends exactly one certificate. Anything extra is
///   refused rather than ignored, so nothing unauthenticated is ever parsed.
/// - **The signature is still verified.** A matching certificate is public; only the daemon
///   holds its key. `verify_tls13_signature` checks the handshake signature (CertificateVerify)
///   against the key inside the pinned certificate using the ring provider's algorithms, which
///   is the proof of key possession.
/// - **TLS 1.3 only.** `verify_tls12_signature` always fails (and the configs are built TLS 1.3
///   only, as QUIC requires).
#[derive(Debug)]
pub struct PinnedServerVerifier {
    pin: Fingerprint,
    algs: WebPkiSupportedAlgorithms,
}

impl PinnedServerVerifier {
    pub fn new(pin: Fingerprint) -> Self {
        Self {
            pin,
            algs: algorithms(),
        }
    }
}

impl ServerCertVerifier for PinnedServerVerifier {
    fn verify_server_cert(
        &self,
        end_entity: &CertificateDer<'_>,
        intermediates: &[CertificateDer<'_>],
        _server_name: &ServerName<'_>,
        _ocsp_response: &[u8],
        _now: UnixTime,
    ) -> Result<ServerCertVerified, Error> {
        if !intermediates.is_empty() {
            tracing::debug!("server sent intermediates; refusing");
            return Err(Error::General(
                "unexpected intermediate certificates".into(),
            ));
        }
        if Fingerprint::of_certificate(end_entity.as_ref()) != self.pin {
            tracing::debug!("server certificate does not match the pinned fingerprint");
            return Err(Error::General(
                "server certificate does not match the pinned fingerprint".into(),
            ));
        }
        Ok(ServerCertVerified::assertion())
    }

    fn verify_tls12_signature(
        &self,
        _message: &[u8],
        _cert: &CertificateDer<'_>,
        _dss: &DigitallySignedStruct,
    ) -> Result<HandshakeSignatureValid, Error> {
        Err(no_tls12())
    }

    fn verify_tls13_signature(
        &self,
        message: &[u8],
        cert: &CertificateDer<'_>,
        dss: &DigitallySignedStruct,
    ) -> Result<HandshakeSignatureValid, Error> {
        check_scheme(dss)?;
        crypto::verify_tls13_signature(message, cert, dss, &self.algs)
    }

    fn supported_verify_schemes(&self) -> Vec<SignatureScheme> {
        vec![SCHEME]
    }
}

/// Server side: accepts only clients that present a registered public key (RFC 7250 raw public
/// key) and prove possession of it.
///
/// - **Mandatory.** A client that sends no key is refused (`client_auth_mandatory` is true).
/// - **Raw public keys only.** `requires_raw_public_keys` is true, so a client offering an X.509
///   certificate fails negotiation. The "certificate" the client sends is its bare
///   SubjectPublicKeyInfo.
/// - **Registry lookup on every handshake.** `verify_client_cert` checks the SPKI against the
///   [`KeyRegistry`] at that moment. Revocation therefore takes effect on the next handshake.
///   Intermediates are rejected.
/// - **The signature is verified** against that SPKI with `verify_tls13_signature_with_raw_key`.
///   Without it, anyone who had seen a registered public key could claim it.
/// - **TLS 1.3 only**, as for the client.
#[derive(Debug)]
pub struct RegisteredClientVerifier {
    registry: KeyRegistry,
    algs: WebPkiSupportedAlgorithms,
}

impl RegisteredClientVerifier {
    pub fn new(registry: KeyRegistry) -> Self {
        Self {
            registry,
            algs: algorithms(),
        }
    }
}

impl ClientCertVerifier for RegisteredClientVerifier {
    fn root_hint_subjects(&self) -> &[DistinguishedName] {
        &[]
    }

    fn verify_client_cert(
        &self,
        end_entity: &CertificateDer<'_>,
        intermediates: &[CertificateDer<'_>],
        _now: UnixTime,
    ) -> Result<ClientCertVerified, Error> {
        if !intermediates.is_empty() {
            return Err(Error::General(
                "unexpected intermediate certificates".into(),
            ));
        }
        let key = PublicKey::from_spki_der(end_entity.as_ref());
        if !self.registry.contains(&key) {
            tracing::debug!(?key, "client key is not registered; refusing");
            return Err(Error::General("client key is not registered".into()));
        }
        Ok(ClientCertVerified::assertion())
    }

    fn verify_tls12_signature(
        &self,
        _message: &[u8],
        _cert: &CertificateDer<'_>,
        _dss: &DigitallySignedStruct,
    ) -> Result<HandshakeSignatureValid, Error> {
        Err(no_tls12())
    }

    fn verify_tls13_signature(
        &self,
        message: &[u8],
        cert: &CertificateDer<'_>,
        dss: &DigitallySignedStruct,
    ) -> Result<HandshakeSignatureValid, Error> {
        check_scheme(dss)?;
        let spki = SubjectPublicKeyInfoDer::from(cert.as_ref());
        crypto::verify_tls13_signature_with_raw_key(message, &spki, dss, &self.algs)
    }

    fn supported_verify_schemes(&self) -> Vec<SignatureScheme> {
        vec![SCHEME]
    }

    fn requires_raw_public_keys(&self) -> bool {
        true
    }
}
